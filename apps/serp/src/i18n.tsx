export type Lang = "tr" | "en";

export function stored<T>(key: string, fallback: T): T {
  try {
    const raw = localStorage.getItem(key);
    return raw ? (JSON.parse(raw) as T) : fallback;
  } catch {
    return fallback;
  }
}
export function persist(key: string, value: unknown) {
  try {
    localStorage.setItem(key, JSON.stringify(value));
  } catch {
    /* Storage can be disabled in browser previews. */
  }
}

type Translate = (key: Key, values?: Record<string, string | number>) => string;
const fill = (text: string, values?: Record<string, string | number>) =>
  values ? text.replace(/\{(\w+)\}/g, (match, name: string) => String(values[name] ?? match)) : text;

const Context = createContext<{ lang: Lang; setLang: (lang: Lang) => void; t: Translate }>({
  lang: "tr",
  setLang: () => {},
  t: (key, values) => fill(tr[key], values),
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, update] = useState<Lang>(() => stored("serp.language", "tr"));
  // CSS uppercase follows the page language: Turkish turns "i" into "İ".
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);
  const setLang = (next: Lang) => {
    update(next);
    persist("serp.language", next);
  };
  const t: Translate = (key, values) => fill((lang === "tr" ? tr : en)[key], values);
  return <Context.Provider value={{ lang, setLang, t }}>{children}</Context.Provider>;
}
export const useI18n = () => useContext(Context);

/** Whether a dynamic key (a reason or a feature) has a text. */
export const hasKey = (key: string): key is Key => key in en;

export function number(value: number, lang: Lang, digits = 1) {
  return new Intl.NumberFormat(lang === "tr" ? "tr-TR" : "en-US", { maximumFractionDigits: digits }).format(value);
}
export function percent(share: number, lang: Lang, digits = 0) {
  return new Intl.NumberFormat(lang === "tr" ? "tr-TR" : "en-US", { style: "percent", maximumFractionDigits: digits }).format(share);
}
export function usd(value: number, lang: Lang) {
  return new Intl.NumberFormat(lang === "tr" ? "tr-TR" : "en-US", {
    style: "currency",
    currency: "USD",
    maximumFractionDigits: value > 0 && value < 0.1 ? 4 : 2,
  }).format(value);
}
export function date(value: string, lang: Lang) {
  const parsed = new Date(value);
  return Number.isNaN(parsed.getTime())
    ? value
    : new Intl.DateTimeFormat(lang === "tr" ? "tr-TR" : "en-US", { dateStyle: "medium", timeStyle: "short" }).format(parsed);
}
