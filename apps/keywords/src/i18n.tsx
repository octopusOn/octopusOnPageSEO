export function number(value: number, lang: Lang, digits = 1) {
  return new Intl.NumberFormat(lang === "tr" ? "tr-TR" : "en-US", { maximumFractionDigits: digits }).format(value);
}
export function usd(value: number, lang: Lang) {
  return new Intl.NumberFormat(lang === "tr" ? "tr-TR" : "en-US", {
    style: "currency",
    currency: "USD",
    maximumFractionDigits: value > 0 && value < 0.1 ? 4 : 2,
  }).format(value);
}
export function date(value: string, lang: Lang) {
  const parsed = new Date(value);
  return Number.isNaN(parsed.getTime())
    ? value
    : new Intl.DateTimeFormat(lang === "tr" ? "tr-TR" : "en-US", { dateStyle: "medium", timeStyle: "short" }).format(parsed);
}
export function time(value: string, lang: Lang) {
  const parsed = new Date(value);
  return Number.isNaN(parsed.getTime())
    ? value
    : new Intl.DateTimeFormat(lang === "tr" ? "tr-TR" : "en-US", { timeStyle: "short" }).format(parsed);
}
