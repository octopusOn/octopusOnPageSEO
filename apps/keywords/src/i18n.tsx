export type Lang = "tr" | "en";

export function stored<T>(key: string, fallback: T): T {
  try {
    const raw = localStorage.getItem(key);
    return raw ? (JSON.parse(raw) as T) : fallback;
  } catch {
    return fallback;
  }
}
export function persist(key: string, value: unknown) {
  try {
    localStorage.setItem(key, JSON.stringify(value));
  } catch {
    /* Storage can be disabled in browser previews. */
  }
}

type Translate = (key: Key, values?: Record<string, string | number>) => string;
const fill = (text: string, values?: Record<string, string | number>) =>
  values ? text.replace(/\{(\w+)\}/g, (match, name: string) => String(values[name] ?? match)) : text;

/** The text of a key; dynamic keys without a text show the key's last part. */
const lookup = (table: Record<string, string>, key: string) => table[key] ?? key.split(".").pop() ?? key;

const Context = createContext<{ lang: Lang; setLang: (lang: Lang) => void; t: Translate }>({
  lang: "tr",
  setLang: () => {},
  t: (key, values) => fill(lookup(tr, key), values),
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, update] = useState<Lang>(() => stored("keywords.language", "tr"));
  // CSS uppercase follows the page language: Turkish turns "i" into "İ".
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);
  const setLang = (next: Lang) => {
    update(next);
    persist("keywords.language", next);
  };
  const t: Translate = (key, values) => fill(lookup(lang === "tr" ? tr : en, key), values);
  return <Context.Provider value={{ lang, setLang, t }}>{children}</Context.Provider>;
}
export const useI18n = () => useContext(Context);

/** Whether a dynamic key has a text. */
export const hasKey = (key: string): key is Key => key in en;

