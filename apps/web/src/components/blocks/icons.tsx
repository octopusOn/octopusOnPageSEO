/** The icons editors can pick in the CMS (apps/cms/config/cms.php `icons`). */
const ICONS: Record<string, LucideIcon> = {
  bell: Bell,
  "book-open": BookOpen,
  bot: Bot,
  "bot-message-square": BotMessageSquare,
  "chart-column-big": ChartColumnBig,
  "chart-line": ChartLine,
  "circle-check": CircleCheck,
  code: Code,
  database: Database,
  download: Download,
  earth: Earth,
  "file-search": FileSearch,
  "file-text": FileText,
  folder: Folder,
  gauge: Gauge,
  "git-compare": GitCompare,
  layers: Layers,
  link: Link,
  lock: Lock,
  network: Network,
  newspaper: Newspaper,
  radar: Radar,
  rocket: Rocket,
  "scroll-text": ScrollText,
  search: Search,
  "shield-check": ShieldCheck,
  "shield-x": ShieldX,
  sparkles: Sparkles,
  target: Target,
  terminal: Terminal,
  zap: Zap,
};

export function CmsIcon({ name, size = 22 }: { name: string | null | undefined; size?: number }) {
  const Icon = name ? ICONS[name] : undefined;
  return Icon ? <Icon size={size} aria-hidden="true" /> : null;
}

export const hasIcon = (name: string | null | undefined): boolean => Boolean(name && ICONS[name]);
