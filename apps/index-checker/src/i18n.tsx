export type Key = keyof typeof tr;

/** Both tables, for tests. */
export const tables = { tr, en };

export function stored<T>(key: string, fallback: T): T {
  try {
    const raw = localStorage.getItem(key);
    return raw ? (JSON.parse(raw) as T) : fallback;
  } catch {
    return fallback;
  }
}

export function persist(key: string, value: unknown): void {
  try {
    localStorage.setItem(key, JSON.stringify(value));
  } catch {
    // ignore storage errors
  }
}

export function number(value: number, lang: Lang): string {
  return new Intl.NumberFormat(lang === "tr" ? "tr-TR" : "en-US", {
    maximumFractionDigits: 0,
  }).format(value);
}

/** A 0–100 score as a percentage: "%45" in Turkish, "45%" in English. */
export function percent(value: number, lang: Lang): string {
  return new Intl.NumberFormat(lang === "tr" ? "tr-TR" : "en-US", {
    style: "percent",
    maximumFractionDigits: 0,
  }).format(value / 100);
}

/** US dollars with cents and fractions of a cent (credit charges are small). */
export function usd(value: number, lang: Lang): string {
  return new Intl.NumberFormat(lang === "tr" ? "tr-TR" : "en-US", {
    style: "currency",
    currency: "USD",
    minimumFractionDigits: 2,
    maximumFractionDigits: 4,
  }).format(value);
}

export type Translate = (
  key: Key,
  values?: Record<string, string | number>,
) => string;

const fill = (text: string, values?: Record<string, string | number>) =>
  values
    ? text.replace(/\{(\w+)\}/g, (match, name: string) =>
        String(values[name] ?? match),
      )
    : text;

const Context = createContext<{
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: Translate;
}>({
  lang: "tr",
  setLang: () => {},
  t: (k, values) => fill(tr[k], values),
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() =>
    stored<Lang>("finder.lang", "tr"),
  );
  // CSS uppercase follows the page language: Turkish turns "i" into "İ".
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);
  const setLang = (next: Lang) => {
    setLangState(next);
    persist("finder.lang", next);
  };
  const dict = lang === "tr" ? tr : en;
  return (
    <Context.Provider
      value={{ lang, setLang, t: (k, values) => fill(dict[k], values) }}
    >
      {children}
    </Context.Provider>
  );
}

export function useI18n() {
  return useContext(Context);
}
