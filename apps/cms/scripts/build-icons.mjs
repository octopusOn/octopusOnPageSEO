// Writes resources/js/icons.js and resources/icons.json: the Lucide icons the admin draws (its
// own UI and the content icons of config/cms.php) as plain SVG data, for Alpine templates and
// for the `<x-icon>` Blade component. The icon data comes from apps/web's lucide-react,
// so the admin needs no icon package of its own. Run `pnpm --filter @octopusseo/cms icons` after
// adding an icon to config/cms.php or to UI_ICONS.

import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const UI_ICONS = [
  "arrow-down", "arrow-right-left", "arrow-up", "check", "chevron-down", "chevron-right", "circle-alert",
  "copy", "corner-down-right", "external-link", "eye", "file-text", "folder-tree", "globe", "grip-vertical",
  "image", "languages", "layout-dashboard", "log-out", "pencil", "plus", "refresh-cw", "save", "search",
  "settings", "trash-2", "upload", "users", "x",
];

const config = readFileSync(path.join(here, "../config/cms.php"), "utf8");
const block = /'icons' => \[([\s\S]*?)\]/.exec(config)?.[1] ?? "";
const contentIcons = [...block.matchAll(/'([a-z0-9-]+)'/g)].map((m) => m[1]);
const names = [...new Set([...UI_ICONS, ...contentIcons])].sort();

const require = createRequire(path.join(here, "../../web/package.json"));
const root = path.dirname(require.resolve("lucide-react/package.json"));
/** An icon's data; alias modules (`trash-2`) re-export another icon. */
async function iconData(name) {
  const file = path.join(root, "dist/esm/icons", `${name}.mjs`);
  const module = await import(pathToFileURL(file).href);
  if (module.__iconData) return module.__iconData;
  const target = /from '\.\/([a-z0-9-]+)\.mjs'/.exec(readFileSync(file, "utf8"))?.[1];
  if (!target) throw new Error(`${name} is not a Lucide icon`);
  return iconData(target);
}

const icons = {};
for (const name of names) {
  icons[name] = (await iconData(name)).node.map(([tag, attrs]) => {
    const { key: _key, ...rest } = attrs;
    return [tag, rest];
  });
}

writeFileSync(
  path.join(here, "../resources/js/icons.js"),
  `// Generated by scripts/build-icons.mjs from Lucide (ISC license, https://lucide.dev). Do not edit.\n\n` +
    `export const ICONS = ${JSON.stringify(icons)};\n`,
);
writeFileSync(path.join(here, "../resources/icons.json"), `${JSON.stringify(icons)}\n`);
console.log(`Wrote ${names.length} icons.`);
