export type Key = keyof typeof en;
export type Lang = "tr" | "en";
export function stored<T>(key: string, fallback: T): T {
  try {
    const raw = localStorage.getItem(key);
    return raw ? (JSON.parse(raw) as T) : fallback;
  } catch {
    return fallback;
  }
}
export function persist(key: string, value: unknown) {
  try {
    localStorage.setItem(key, JSON.stringify(value));
  } catch {
    /* Storage can be disabled in browser previews. */
  }
}
const Context = createContext<{
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: Key) => string;
}>({ lang: "tr", setLang: () => {}, t: (k) => tr[k] });
export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, update] = useState<Lang>(() => stored("spider.language", "tr"));
  // CSS uppercase follows the page language: Turkish turns "i" into "İ".
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);
  const setLang = (l: Lang) => {
    update(l);
    persist("spider.language", l);
  };
  return (
    <Context.Provider
      value={{ lang, setLang, t: (key) => (lang === "tr" ? tr : en)[key] }}
    >
      {children}
    </Context.Provider>
  );
}
export const useI18n = () => useContext(Context);
export function number(value: number, lang: Lang) {
  return new Intl.NumberFormat(lang === "tr" ? "tr-TR" : "en-US", {
    maximumFractionDigits: 1,
  }).format(value);
}
export function duration(ms: number) {
  const s = Math.floor(ms / 1000);
  return `${Math.floor(s / 3600)
    .toString()
    .padStart(2, "0")}:${Math.floor((s / 60) % 60)
    .toString()
    .padStart(2, "0")}:${(s % 60).toString().padStart(2, "0")}`;
}
